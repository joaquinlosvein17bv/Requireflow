import { Database } from "bun:sqlite";
import os from "node:os";
import path from "node:path";
import { createDatabase, getDatabase } from "./connection.ts";
import {
  createProject,
  deleteProject,
  listProjects,
} from "../domain/project.ts";
import { createSection, listSections } from "../domain/section.ts";
import { createTask, startTask, completeTask } from "../domain/task.ts";
import { archiveDoneTasks } from "../domain/archive.ts";
import { listHistory } from "../domain/history.ts";

/**
 * Demo fixtures live in their own database and never touch real projects.
 *
 * The previous implementation deleted a project by name and wrote a hardcoded
 * `C:/proyectos/...` root into whatever database was open (RF-23).
 */
export const DEMO_PROJECT_NAME = "Demo · SaaS E-Commerce Platform";

export function defaultDemoDbPath(): string {
  return path.join(os.homedir(), ".requireflow", "demo.db");
}

export interface SeedOptions {
  /** Defaults to the isolated demo database, never the main one. */
  db?: Database;
  /** Rebuilds the demo project. Only the demo project by id is removed. */
  reset?: boolean;
}

export interface SeedResult {
  projectId: string;
  tasks: number;
  archived: number;
  historyRows: number;
  reused: boolean;
}

function summarize(db: Database, projectId: string, reused: boolean): SeedResult {
  const tasks = db
    .query("SELECT COUNT(*) as c FROM tasks WHERE project_id = ?")
    .get(projectId) as { c: number };
  const archived = db
    .query("SELECT COUNT(*) as c FROM tasks WHERE project_id = ? AND status = 'archived'")
    .get(projectId) as { c: number };

  return {
    projectId,
    tasks: Number(tasks.c),
    archived: Number(archived.c),
    historyRows: listHistory(projectId, 1, 1, db).total,
    reused,
  };
}

function minutesAgo(minutes: number): string {
  return new Date(Date.now() - minutes * 60_000).toISOString();
}

function daysAgo(days: number): string {
  return new Date(Date.now() - days * 86_400_000).toISOString();
}

export function seedDemoData(options: SeedOptions = {}): SeedResult {
  const db = options.db ?? getDatabase(defaultDemoDbPath());

  const existing = listProjects(db).find((project) => project.name === DEMO_PROJECT_NAME);
  if (existing && !options.reset) {
    return summarize(db, existing.id, true);
  }
  if (existing) {
    // Delete by id, and only the demo project, never by name matching.
    deleteProject(existing.id, db);
  }

  const project = createProject(
    {
      name: DEMO_PROJECT_NAME,
      description: "Demo dataset generated by RequireFlow. Safe to rebuild with --reset.",
      archiveThresholdHours: 24,
    },
    db
  );

  const sections = listSections(project.id, db);
  const general = sections.find((section) => section.name === "General");
  const frontend = sections.find((section) => section.name === "Frontend");
  const backend = sections.find((section) => section.name === "Backend");
  const bugfixes = sections.find((section) => section.name === "Bugfixes");

  const databaseSection = createSection(
    { projectId: project.id, name: "Database & Cache", color: "#f59e0b" },
    db
  );
  const securitySection = createSection(
    { projectId: project.id, name: "Security & Auth", color: "#ec4899" },
    db
  );

  // --- Queue ---
  createTask(
    {
      projectId: project.id,
      sectionId: bugfixes?.id,
      title: "500 when a 3D Secure card is confirmed by webhook",
      description: "Bank OTP confirmation makes the webhook retry and duplicate the charge.",
      type: "bugfix",
      priority: "blocker",
      storyPoints: 5,
    },
    db
  );
  createTask(
    {
      projectId: project.id,
      sectionId: securitySection.id,
      title: "Social login with Google and GitHub",
      description: "One-click sign in with JWT access token and refresh token rotation.",
      type: "feature",
      priority: "high",
      storyPoints: 5,
    },
    db
  );
  createTask(
    {
      projectId: project.id,
      sectionId: frontend?.id,
      title: "Interactive filters by price, category and rating",
      description: "Collapsible sidebar with instant search on the catalogue page.",
      type: "feature",
      priority: "medium",
      storyPoints: 3,
    },
    db
  );
  createTask(
    {
      projectId: project.id,
      sectionId: databaseSection.id,
      title: "Cache featured products with Redis",
      description: "Reduce load on the primary database with a one hour TTL.",
      type: "chore",
      priority: "medium",
      storyPoints: 2,
    },
    db
  );

  // --- In progress ---
  const realtime = createTask(
    {
      projectId: project.id,
      sectionId: backend?.id,
      title: "Real time shipping notifications over WebSockets",
      description: "Notify the buyer when the package moves to 'in transit'.",
      type: "feature",
      priority: "high",
      storyPoints: 8,
    },
    db
  );
  startTask(realtime.id, db);
  db.run("UPDATE tasks SET started_at = ? WHERE id = ?", [minutesAgo(45), realtime.id]);

  const nPlusOne = createTask(
    {
      projectId: project.id,
      sectionId: databaseSection.id,
      title: "Remove an N+1 query from the order list",
      description: "Eager load order lines and related products.",
      type: "refactor",
      priority: "medium",
      storyPoints: 3,
    },
    db
  );
  startTask(nPlusOne.id, db);
  db.run("UPDATE tasks SET started_at = ? WHERE id = ?", [minutesAgo(18), nPlusOne.id]);

  // --- Archive history (backdated completions) ---
  const historical: Array<{
    title: string;
    type: "feature" | "bugfix" | "chore" | "refactor";
    priority: "low" | "medium" | "high" | "blocker";
    notes: string;
    cycleMinutes: number;
    daysAgo: number;
  }> = [
    {
      title: "CI pipeline on GitHub Actions",
      type: "chore",
      priority: "high",
      notes: "Tests, typecheck and build run on every pull request.",
      cycleMinutes: 32,
      daysAgo: 5,
    },
    {
      title: "SQLite WAL migration",
      type: "feature",
      priority: "blocker",
      notes: "Foreign keys enabled and the FTS5 index created.",
      cycleMinutes: 48,
      daysAgo: 4,
    },
    {
      title: "Memory leak in the WebSocket listener",
      type: "bugfix",
      priority: "high",
      notes: "Removed a duplicated listener on disconnect.",
      cycleMinutes: 22,
      daysAgo: 3,
    },
    {
      title: "Checkout modal and order summary",
      type: "feature",
      priority: "medium",
      notes: "Card validation with immediate visual feedback.",
      cycleMinutes: 40,
      daysAgo: 2,
    },
    {
      title: "WebP image compression in the storage bucket",
      type: "refactor",
      priority: "low",
      notes: "65% smaller catalogue images.",
      cycleMinutes: 15,
      daysAgo: 1,
    },
  ];

  for (const item of historical) {
    const task = createTask(
      {
        projectId: project.id,
        sectionId: general?.id,
        title: item.title,
        type: item.type,
        priority: item.priority,
      },
      db
    );

    startTask(task.id, db);
    db.run("UPDATE tasks SET started_at = ? WHERE id = ?", [
      minutesAgo(item.daysAgo * 1440 + item.cycleMinutes),
      task.id,
    ]);
    completeTask(task.id, item.notes, db);

    // Place the completion in the past for both the task and its cycle so the
    // metrics window and the daily trend show a realistic history.
    const completedAt = daysAgo(item.daysAgo);
    db.run("UPDATE tasks SET completed_at = ? WHERE id = ?", [completedAt, task.id]);
    db.run("UPDATE task_cycles SET completed_at = ? WHERE task_id = ?", [completedAt, task.id]);
  }

  const archived = archiveDoneTasks(project.id, true, 0, db);

  // --- Recently completed, still on the board ---
  const cors = createTask(
    {
      projectId: project.id,
      sectionId: securitySection.id,
      title: "CORS headers on the OPTIONS preflight",
      type: "bugfix",
      priority: "high",
      storyPoints: 2,
    },
    db
  );
  startTask(cors.id, db);
  db.run("UPDATE tasks SET started_at = ? WHERE id = ?", [minutesAgo(25), cors.id]);
  completeTask(cors.id, "Added the allow-origin and allow-methods headers.", db);
  db.run("UPDATE task_cycles SET completed_at = ? WHERE task_id = ?", [
    minutesAgo(5),
    cors.id,
  ]);
  db.run("UPDATE tasks SET completed_at = ? WHERE id = ?", [minutesAgo(5), cors.id]);

  const navbar = createTask(
    {
      projectId: project.id,
      sectionId: frontend?.id,
      title: "Responsive navigation bar",
      type: "feature",
      priority: "medium",
      storyPoints: 3,
    },
    db
  );
  startTask(navbar.id, db);
  db.run("UPDATE tasks SET started_at = ? WHERE id = ?", [minutesAgo(60), navbar.id]);
  completeTask(navbar.id, "Mobile menu and cart badge.", db);
  db.run("UPDATE task_cycles SET completed_at = ? WHERE task_id = ?", [
    minutesAgo(15),
    navbar.id,
  ]);
  db.run("UPDATE tasks SET completed_at = ? WHERE id = ?", [minutesAgo(15), navbar.id]);

  const result = summarize(db, project.id, false);
  return { ...result, archived: archived.archivedCount + result.archived, reused: false };
}

if (import.meta.main) {
  const dbPath = process.env.REQUIREFLOW_DEMO_DB_PATH || defaultDemoDbPath();
  const reset = process.argv.includes("--reset");
  const db = createDatabase(dbPath);

  const result = seedDemoData({ db, reset });
  console.log(`Demo database: ${dbPath}`);
  console.log(
    result.reused
      ? `Demo project already present (${result.projectId}). Use --reset to rebuild it.`
      : `Seeded demo project ${result.projectId}: ${result.tasks} tasks, ${result.historyRows} history rows.`
  );
  console.log(`Open it with: REQUIREFLOW_DB_PATH="${dbPath}" requireflow ui`);
  db.close();
}
