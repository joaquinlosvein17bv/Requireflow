import { listFindings, listReviews } from "./review.ts";
import { PlanValidationError } from "./scope.ts";

/**
 * Deterministic Markdown projection of the V2 product backlog.
 *
 * SQLite stays the only source of truth. These files are generated output:
 * `--check` regenerates in memory and reports any difference, including a
 * manual edit, so nobody can quietly treat Markdown as a second database.
 */
export interface BacklogExportCounts {
  epics: number;
  stories: number;
  groups: number;
  criteria: number;
  decisions: number;
  reviews: number;
}

export interface BacklogExportResult {
  outDir: string;
  files: string[];
  manifestPath: string;
  counts: BacklogExportCounts;
  verified: boolean;
  schemaVersion: number;
}

export interface BacklogCheckResult {
  upToDate: boolean;
  differences: string[];
  counts: BacklogExportCounts;
}

const GENERATED_NOTICE =
  "> Generated by RequireFlow 2 from the V2 SQLite database. Do not edit by hand: regenerate with `requireflow export`.";

function sha256(value: string): string {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function slugify(value: string): string {
  const normalized = value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
  return normalized === "" ? "project" : normalized.slice(0, 60);
}

function schemaVersion(db: Database): number {
  const row = db
    .query("SELECT COALESCE(MAX(version), 0) v FROM _schema_migrations")
    .get() as { v: number };
  return Number(row.v);
}

interface RenderedBacklog {
  files: Map<string, string>;
  counts: BacklogExportCounts;
  schemaVersion: number;
  projectName: string;
  projectId: string;
}

function renderBacklog(projectId: string, db: Database): RenderedBacklog {
  const project = getProject(projectId, db);
  if (!project) throw new PlanValidationError(`Project not found with ID: ${projectId}`);

  const epics = listWorkItems(projectId, { kind: "epic" }, db);
  const stories = listWorkItems(projectId, { kind: "story" }, db);
  const increments = listIncrements(projectId, db);
  const decisions = listDecisions(projectId, { includeSuperseded: true }, db);
  const version = schemaVersion(db);

  const files = new Map<string, string>();
  const counts: BacklogExportCounts = {
    epics: epics.length,
    stories: stories.length,
    groups: increments.length,
    criteria: 0,
    decisions: decisions.length,
    reviews: 0,
  };

  const storyById = new Map(stories.map((story) => [story.id, story]));
  const storyLine = (story: WorkItem): string =>
    `- \`${story.code ?? "H???"}\` **${story.title}** — estado \`${story.status}\`, definición \`${story.definition}\`, procedencia \`${story.origin}\``;

  // README
  const readme: string[] = [];
  readme.push(`# ${project.name} — Product Backlog`);
  readme.push("");
  readme.push(GENERATED_NOTICE);
  readme.push("");
  readme.push(`- **Project ID:** \`${project.id}\``);
  readme.push(`- **Mode:** \`${project.mode}\``);
  readme.push(`- **Description:** ${project.description ?? "—"}`);
  readme.push(`- **Schema version:** v${version}`);
  readme.push(
    `- **Counts:** ${counts.epics} epics · ${counts.stories} stories · ${counts.groups} groups · ${decisions.length} decisions`
  );
  readme.push("");
  readme.push("## Index");
  readme.push("");
  readme.push("- [Epics and stories](./epics.md)");
  for (const group of increments) {
    readme.push(`- [${group.code}](./groups/${group.code}.md)`);
  }
  readme.push("- [Decisions](./decisions.md)");
  readme.push("");
  files.set("README.md", `${readme.join("\n")}\n`);

  // Epics and their stories
  const epicLines: string[] = [];
  epicLines.push(`# ${project.name} — Epics and stories`);
  epicLines.push("");
  epicLines.push(GENERATED_NOTICE);
  epicLines.push("");
  if (epics.length === 0) {
    epicLines.push("_No epics._");
  }
  for (const epic of epics) {
    epicLines.push(`## ${epic.code ?? "E??"} — ${epic.title}`);
    epicLines.push("");
    epicLines.push(`- **Status:** \`${epic.status}\``);
    epicLines.push(`- **Definition:** \`${epic.definition}\``);
    epicLines.push(`- **Origin:** \`${epic.origin}\``);
    epicLines.push(`- **Description:** ${epic.description ?? "—"}`);
    epicLines.push("");
    const own = stories.filter((story) => story.parent_id === epic.id);
    if (own.length === 0) {
      epicLines.push("_No stories._");
    } else {
      for (const story of own) epicLines.push(storyLine(story));
    }
    epicLines.push("");
  }
  const ungroupedStories = stories.filter((story) => story.parent_id === null);
  if (ungroupedStories.length > 0) {
    epicLines.push("## Stories without epic");
    epicLines.push("");
    for (const story of ungroupedStories) epicLines.push(storyLine(story));
    epicLines.push("");
  }
  files.set("epics.md", `${epicLines.join("\n")}\n`);

  // One file per group
  for (const group of increments) {
    const view = getIncrementView(group.id, db);
    counts.criteria += view.acceptanceCriteria.length;
    const reviews = listReviews(group.id, db);
    counts.reviews += reviews.length;

    const lines: string[] = [];
    lines.push(`# ${group.code} — ${group.name ?? "(sin nombre)"}`);
    lines.push("");
    lines.push(GENERATED_NOTICE);
    lines.push("");
    lines.push("## Scope");
    lines.push("");
    lines.push(`- **Status:** \`${group.status}\``);
    lines.push(`- **Objective:** ${group.goal ?? "—"}`);
    lines.push(`- **Exclusions:** ${group.exclusiones ?? "—"}`);
    lines.push(`- **Order:** ${group.position}`);
    lines.push(`- **Approved revision:** ${group.approved_revision}`);
    lines.push(`- **Approved at:** ${group.approved_at ?? "—"}`);
    lines.push(`- **Approved by:** ${group.approved_by ?? "—"}`);
    lines.push(`- **Scope hash:** \`${group.approved_scope_hash ?? "—"}\``);
    lines.push(`- **Drifted since approval:** ${view.drifted ? "yes" : "no"}`);
    lines.push(`- **Readiness:** ${view.readiness.ready ? "ready" : "not ready"}`);
    lines.push(`- **Next action:** \`${view.nextAction}\``);
    lines.push("");

    if (view.readiness.blockers.length > 0) {
      lines.push("### Blockers");
      lines.push("");
      for (const blocker of view.readiness.blockers) lines.push(`- ${blocker}`);
      lines.push("");
    }

    lines.push("### Dependencies");
    lines.push("");
    if (view.dependencies.length === 0) lines.push("_None._");
    for (const dependency of view.dependencies) {
      lines.push(`- ${dependency.code} — \`${dependency.status}\``);
    }
    lines.push("");

    lines.push("### Stories");
    lines.push("");
    if (view.stories.length === 0) lines.push("_None._");
    for (const story of view.stories) {
      lines.push(storyLine(story));
      const tasks = db
        .query(
          "SELECT id, title, status, odd_task_ref FROM tasks WHERE work_item_id = ? ORDER BY created_at ASC"
        )
        .all(story.id) as Array<{
        id: string;
        title: string;
        status: string;
        odd_task_ref: string | null;
      }>;
      for (const task of tasks) {
        lines.push(
          `  - execution \`${task.id.slice(0, 8)}\` [${task.status}] ${task.title}${task.odd_task_ref ? ` · ODD \`${task.odd_task_ref}\`` : ""}`
        );
      }
    }
    lines.push("");

    lines.push("### Acceptance criteria");
    lines.push("");
    if (view.acceptanceCriteria.length === 0) lines.push("_None._");
    for (const criterion of view.acceptanceCriteria) {
      lines.push(`- \`${criterion.code}\` ${criterion.text} — \`${criterion.status}\``);
    }
    lines.push("");

    lines.push("### Confirmed decisions");
    lines.push("");
    if (view.decisions.length === 0) lines.push("_None._");
    for (const decision of view.decisions) {
      lines.push(`- \`${decision.code}\` **${decision.title}**`);
      lines.push(`  - Question: ${decision.question}`);
      lines.push(`  - Answer: ${decision.answer}`);
      if (decision.impact) lines.push(`  - Impact: ${decision.impact}`);
    }
    lines.push("");

    lines.push("### Reviews");
    lines.push("");
    if (reviews.length === 0) lines.push("_No reviews yet._");
    for (const review of reviews) {
      lines.push(
        `- Cycle ${review.cycle} — \`${review.status}\` · requested by \`${review.requested_by}\` at ${review.requested_at}`
      );
      if (review.evidence) lines.push(`  - Evidence: ${review.evidence}`);
      const findings = listFindings(review.id, db);
      for (const finding of findings) {
        lines.push(
          `  - Defect \`${finding.id.slice(0, 8)}\` (\`${finding.status}\`): ${finding.description}`
        );
      }
    }
    lines.push("");

    const revisions = db
      .query(
        "SELECT revision, scope_hash, approved_at, approved_by FROM increment_revisions WHERE increment_id = ? ORDER BY revision ASC"
      )
      .all(group.id) as Array<{
      revision: number;
      scope_hash: string;
      approved_at: string;
      approved_by: string;
    }>;
    lines.push("### Approved scope revisions");
    lines.push("");
    if (revisions.length === 0) lines.push("_None._");
    for (const revision of revisions) {
      lines.push(
        `- Revision ${revision.revision} · \`${revision.scope_hash.slice(0, 12)}\` · approved by \`${revision.approved_by}\` at ${revision.approved_at}`
      );
    }
    lines.push("");

    files.set(`groups/${group.code}.md`, `${lines.join("\n")}\n`);
  }

  // Decisions
  const decisionLines: string[] = [];
  decisionLines.push(`# ${project.name} — Confirmed decisions`);
  decisionLines.push("");
  decisionLines.push(GENERATED_NOTICE);
  decisionLines.push("");
  if (decisions.length === 0) {
    decisionLines.push("_No decisions recorded._");
  }
  for (const decision of decisions) {
    decisionLines.push(`## ${decision.code} — ${decision.title}`);
    decisionLines.push("");
    decisionLines.push(`- **Status:** \`${decision.status}\``);
    decisionLines.push(`- **Question:** ${decision.question}`);
    decisionLines.push(`- **Answer:** ${decision.answer}`);
    if (decision.alternatives) decisionLines.push(`- **Alternatives:** ${decision.alternatives}`);
    if (decision.impact) decisionLines.push(`- **Impact:** ${decision.impact}`);
    decisionLines.push(`- **Recorded by:** \`${decision.actor}\``);
    decisionLines.push(`- **Version:** ${decision.version}`);
    decisionLines.push("");
  }
  files.set("decisions.md", `${decisionLines.join("\n")}\n`);

  // Recompute story count actually referenced (keeps counts honest)
  counts.stories = new Set([...storyById.keys()]).size;

  return {
    files,
    counts,
    schemaVersion: version,
    projectName: project.name,
    projectId: project.id,
  };
}

function buildManifest(rendered: RenderedBacklog): string {
  const entries: Record<string, string> = {};
  for (const [relative, content] of [...rendered.files.entries()].sort(([a], [b]) =>
    a.localeCompare(b)
  )) {
    entries[relative] = sha256(content);
  }
  return `${JSON.stringify(
    {
      generator: "requireflow",
      format: 1,
      projectId: rendered.projectId,
      projectName: rendered.projectName,
      schemaVersion: rendered.schemaVersion,
      counts: rendered.counts,
      files: entries,
    },
    null,
    2
  )}\n`;
}

export interface ExportBacklogOptions {
  projectId: string;
  outDir: string;
  force?: boolean;
}

export function exportProjectBacklog(
  options: ExportBacklogOptions,
  db: Database = getDatabase()
): BacklogExportResult {
  const rendered = renderBacklog(options.projectId, db);
  const outDir = path.resolve(options.outDir);
  const manifestPath = path.join(outDir, "manifest.json");

  // Manual edits are detected before overwriting.
  if (fs.existsSync(manifestPath) && !options.force) {
    const previous = JSON.parse(fs.readFileSync(manifestPath, "utf8")) as {
      files?: Record<string, string>;
    };
    const modified: string[] = [];
    for (const [relative, expectedHash] of Object.entries(previous.files ?? {})) {
      const filePath = path.join(outDir, relative);
      if (!fs.existsSync(filePath)) {
        modified.push(`${relative} (missing)`);
        continue;
      }
      if (sha256(fs.readFileSync(filePath, "utf8")) !== expectedHash) {
        modified.push(`${relative} (edited manually)`);
      }
    }
    if (modified.length > 0) {
      throw new PlanValidationError(
        `Export blocked: these files were modified outside RequireFlow: ${modified.join(", ")}. ` +
          `Re-run with --force to overwrite them.`
      );
    }
  }

  for (const [relative, content] of rendered.files) {
    const filePath = path.join(outDir, relative);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content, "utf8");
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(manifestPath, buildManifest(rendered), "utf8");

  // Verification: what was written must match what was rendered.
  let verified = true;
  for (const [relative, content] of rendered.files) {
    const filePath = path.join(outDir, relative);
    if (fs.readFileSync(filePath, "utf8") !== content) verified = false;
  }
  if (fs.readFileSync(manifestPath, "utf8") !== buildManifest(rendered)) verified = false;

  return {
    outDir,
    files: [...rendered.files.keys()].map((relative) => path.join(outDir, relative)),
    manifestPath,
    counts: rendered.counts,
    verified,
    schemaVersion: rendered.schemaVersion,
  };
}

export interface CheckBacklogOptions {
  projectId: string;
  outDir: string;
}

export function checkProjectBacklog(
  options: CheckBacklogOptions,
  db: Database = getDatabase()
): BacklogCheckResult {
  const rendered = renderBacklog(options.projectId, db);
  const outDir = path.resolve(options.outDir);
  const manifestPath = path.join(outDir, "manifest.json");
  const differences: string[] = [];

  if (!fs.existsSync(manifestPath)) {
    differences.push("manifest.json is missing: run `requireflow export` first");
  }

  for (const [relative, expected] of rendered.files) {
    const filePath = path.join(outDir, relative);
    if (!fs.existsSync(filePath)) {
      differences.push(`${relative} is missing`);
      continue;
    }
    if (fs.readFileSync(filePath, "utf8") !== expected) {
      differences.push(`${relative} differs from the database`);
    }
  }

  if (fs.existsSync(manifestPath) && fs.readFileSync(manifestPath, "utf8") !== buildManifest(rendered)) {
    differences.push("manifest.json is stale");
  }

  return {
    upToDate: differences.length === 0,
    differences,
    counts: rendered.counts,
  };
}

